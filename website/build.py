#!/usr/bin/env python3
"""Bundle src/ into one self-contained page.

  python3 build.py            -> dist/index.html  (deployed by Vercel; also opens straight from disk)
  python3 build.py --fragment OUT.html -> same page without the <html>/<head>/<body> wrapper
"""
import json, pathlib, re, shutil, subprocess, sys

ROOT = pathlib.Path(__file__).parent
SRC = ROOT / 'src'

def scripts():
    order = ['i18n.js', 'signs-official.js', 'photos.js', 'scenes.js', 'topics.js', 'plan.js']
    files = [SRC / f for f in order]
    files += sorted((SRC / 'questions').glob('*.js')) + sorted((SRC / 'lessons').glob('*.js'))
    files += sorted((SRC / 'sv').rglob('*.js'))
    files += [SRC / 'strings.js', SRC / 'app.js']
    out = []
    for f in files:
        code = f.read_text(encoding='utf-8').replace('</script', '<\\/script')
        out.append(f'<script>/* {f.relative_to(SRC)} */\n{code}\n</script>')
    return '\n'.join(out)

def fragment():
    shell = (SRC / 'shell.html').read_text(encoding='utf-8')
    return shell.replace('/*STYLE*/', (SRC / 'styles.css').read_text(encoding='utf-8')).replace('<!--SCRIPTS-->', scripts())

def plan_titles():
    """Day titles from src/plan.js and src/sv/plan.js, for the server's reminder messages."""
    js = ("const vm=require('vm'),fs=require('fs');const c={SV:{plan:{}}};c.window=c;vm.createContext(c);"
          "for(const f of process.argv.slice(1))vm.runInContext(fs.readFileSync(f,'utf8'),c);"
          "console.log(JSON.stringify({en:c.PLAN.map(d=>d.title),sv:c.PLAN.map(d=>(c.SV.plan[d.day]||{}).title||d.title)}))")
    out = subprocess.run(['node', '-e', js, str(SRC / 'plan.js'), str(SRC / 'sv' / 'plan.js')], capture_output=True, text=True, encoding='utf-8', check=True).stdout
    titles = json.loads(out)
    assert len(titles['en']) == 30 and len(titles['sv']) == 30, 'expected 30 plan days'
    return titles

def page():
    frag = fragment()
    head, body = frag.split('<div class="shell">', 1)
    return ('<!doctype html>\n<html lang="sv">\n<head>\n<meta charset="utf-8">\n'
            '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n'
            f'{head}</head>\n<body>\n<div class="shell">{body}</body>\n</html>\n')

if __name__ == '__main__':
    if len(sys.argv) > 2 and sys.argv[1] == '--fragment':
        pathlib.Path(sys.argv[2]).write_text(fragment(), encoding='utf-8')
        print('wrote', sys.argv[2])
    else:
        out = ROOT / 'dist' / 'index.html'
        out.parent.mkdir(exist_ok=True)
        out.write_text(page(), encoding='utf-8')
        for f in (SRC / 'static').iterdir():
            if f.is_dir(): shutil.copytree(f, ROOT / 'dist' / f.name, dirs_exist_ok=True)
            else: shutil.copy2(f, ROOT / 'dist' / f.name)
        api = ROOT.parent / 'api' / '_plan.js'
        api.write_text('// Generated by website/build.py from website/src/plan.js and website/src/sv/plan.js. Do not edit.\nexport default ' + json.dumps(plan_titles(), ensure_ascii=False, indent=2) + ';\n', encoding='utf-8')
        print('wrote', out, f'({out.stat().st_size // 1024} KB), static files and', api.name)
